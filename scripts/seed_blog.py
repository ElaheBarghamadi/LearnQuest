def hex2rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def make_cover(slug, p1, p2, seed):
    global random
    rng = random.Random(seed)
    W, H = 1200, 675
    c1, c2 = hex2rgb(p1), hex2rgb(p2)
    img = Image.new('RGB', (W, H))
    dr = ImageDraw.Draw(img)

    for y in range(H):
        for_ratio = y / H
        base = [int(c1[i] + (c2[i] - c1[i]) * for_ratio) for i in range(3)]
        dr.line([(0, y), (W, y)], fill=tuple(base))

    overlay = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    od = ImageDraw.Draw(overlay)
    for _ in range(9):
        r = rng.randint(60, 220)
        x, y = rng.randint(-r, W), rng.randint(-r, H)
        od.ellipse([x, y, x + r * 2, y + r * 2],
                   fill=(255, 255, 255, rng.randint(12, 34)))

    pts = []
    for x in range(0, W + 25, 25):
        pts.append((x, H - 130 + math.sin(x / 95 + seed) * 45))
    pts += [(W, H), (0, H)]
    od.polygon(pts, fill=(255, 255, 255, 26))
    img = Image.alpha_composite(img.convert('RGBA'), overlay).convert('RGB')
    path = os.path.join(COVERS_DIR, f'{slug}.jpg')
    img.save(path, 'JPEG', quality=88)
    return f'blog_images/{slug}.jpg'


